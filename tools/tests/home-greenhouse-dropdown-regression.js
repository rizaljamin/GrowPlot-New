'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('app/src/main/assets/account-login.js','utf8');
assert.match(source,/syncHomeGreenhouseOptions\(desired\)/,'Home plot selection refreshes its greenhouse options');
assert.match(source,/plot\.greenhouseCount=gh/,'Plot Management greenhouse count is saved on the selected plot');
const declaration=source.match(/let homeGreenhousePlotId='';\s*function syncHomeGreenhouseOptions\(plotId\)\{[\s\S]*?\n\}/);
assert(declaration,'Home greenhouse dropdown synchronizer is present');
const select={value:'2',options:[],events:[],replaceChildren(){this.options=[]},appendChild(option){this.options.push(option)},dispatchEvent(event){this.events.push(event.type)}};
const plots=[{id:'plot-1',greenhouseCount:3},{id:'plot-2',greenhouseCount:1}];
const context={plots,document:{getElementById:id=>id==='gh'?select:null,createElement:()=>({})},Event:class{constructor(type){this.type=type}}};
vm.runInNewContext(declaration[0],context);
vm.runInNewContext("syncHomeGreenhouseOptions('plot-1')",context);
assert.deepEqual(select.options.map(option=>option.value),['1','2','3']);
assert.equal(select.value,'1','first selected plot defaults to Greenhouse 1');
select.value='3';
vm.runInNewContext("syncHomeGreenhouseOptions('plot-1')",context);
assert.equal(select.value,'3','same plot keeps a valid greenhouse selection');
vm.runInNewContext("syncHomeGreenhouseOptions('plot-2')",context);
assert.deepEqual(select.options.map(option=>option.value),['1'],'a one-greenhouse plot has only one Home option');
assert.equal(select.value,'1','changing to a one-greenhouse plot selects Greenhouse 1');
assert(select.events.includes('change'),'a reset greenhouse selection refreshes the Home view');
console.log('PASS: Home greenhouse options follow each plot count and default to Greenhouse 1.');
