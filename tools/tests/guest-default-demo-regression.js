'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const java=fs.readFileSync('app/src/main/java/com/growplot/farm/MainActivity.java','utf8');
const auth=fs.readFileSync('app/src/main/java/com/growplot/farm/AccountApiBridge.java','utf8');
const ui=fs.readFileSync('app/src/main/assets/account-login.js','utf8');
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
const rules=fs.readFileSync('firestore.rules','utf8');
assert.match(auth,/@JavascriptInterface public void ensureGuestSession\(\)/,'Android guest session entrypoint');
assert.match(auth,/if\(session\.isAnonymous\(\)\)guestSessionResponse\(\);\s*else accountResponse\("login",session\)/,'registered session restored without creating guest');
assert.match(auth,/auth\.signInAnonymously\(\)/,'Firebase anonymous auth used, no shared password');
assert.match(auth,/profile\.put\("id","Guest"\)/,'Guest identity maps to existing shared Guest document ID');
assert.match(auth,/profile\.put\("plotId","plot-1"\)/,'Guest defaults to shared Demo Plot');
assert.match(auth,/@JavascriptInterface public void logout\(\)\{[\s\S]*?auth\.signOut\(\);\s*ensureGuestSession\(\)/,'registered logout transitions back to Guest');
assert.match(ui,/api\?\.ensureGuestSession\?\.\(\)/,'guest sign-in starts on every app launch');
assert.match(ui,/if\(response\?\.action==='guestSession'\)/,'guest response is handled');
assert.match(ui,/if\(currentUser\)return/,'late guest response cannot replace registered user');
assert.match(ui,/window\.GrowPlotGuestIdentity='Guest'/,'UI logical Guest identity');
assert.match(ui,/plots\.splice\(0,plots\.length,existing\|\|\{id:'plot-1'/,'guest UI shows Demo only');
assert.match(ui,/window\.GrowPlotGuestIdentity=null/,'registered login discards guest identity');
assert.match(java,/private void returnToDemoStreams\(\) \{[\s\S]*?loadAssignedStreams\("plot-1", "greenhouse-1", true\)/,'Demo logout uses existing Firebase stream code');
assert.match(java,/userStreamMode = true/,'Firebase streaming is default');
assert.doesNotMatch(java,/userStreamMode = false/,'old local player fallback cannot start');
assert.match(java,/if \(user == null && "plot-1"\.equals\(plotId\)\) \{\s*\/\/ Wait for the anonymous Firebase session/,'wait for Auth, do not use local IPs');
assert.match(java,/store\.collection\("feed_assignments"\)\.whereEqualTo\("plotId","plot-1"\)/,'read existing shared Demo assignments');
assert.match(java,/store\.collection\("data_feeds"\)\.document\(ownerUid\+"_"\+deviceId\)/,'use existing Firebase device IP configuration');
assert.match(java,/if \(route\.startsWith\("rtsp:\/\/"\)/,'CCTV03 assigned to first window uses RTSP credentials');
assert.match(java,/String\[\] credentials = vigiCctv03Credentials\(\)/,'credentials not stored as public guest profile');
assert.match(html,/selectedPlotId='plot-1';/,'initial selected plot set to Demo');
assert.match(html,/selectedPlot\.id==="plot-1"&&i<=3/,'no stale local IP WebView sources in Demo');
assert.match(html,/if\(i===1&&selectedPlot\.id!=='plot-1'\)/,'no local IP retry for Demo');
assert.match(rules,/match \/feed_assignments\/\{assignmentId\}/,'original Firebase assignment rules still used');
assert.match(rules,/match \/data_feeds\/\{deviceId\}/,'original Firebase device read rules still used');
assert(!auth.includes('document("Guest").set('),'existing shared Guest record is never overwritten');
assert(!auth.includes('signInWithCustomToken('),'no shared privileged Firebase credentials');
console.log('PASS: Guest anonymous Firebase auth, Demo-only UI, existing CCTV mapping, preserved registered login, no local stream fallback.');
