assert.doesNotMatch(java,/userStreamMode = false/,'guest never switches to static IP streaming mode');
assert.match(java,/\.whereEqualTo\("ownerUserId",uid\)/,'private user plot assignment query preserved');
assert.match(java,/String\[\] credentials = vigiCctv03Credentials\(\)/,'protected VIGI RTSP credentials stay local on device');
assert.match(html,/selectedPlot\.id==='plot-1'&&i<=3/,'Demo Plot no longer loads stale local IP thumbnail');
