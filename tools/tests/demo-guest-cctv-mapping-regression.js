'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const cloud=fs.readFileSync('functions/index.js','utf8');
const java=fs.readFileSync('app/src/main/java/com/growplot/farm/MainActivity.java','utf8');
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
const a=cloud.indexOf('function demoLanHost('),b=cloud.indexOf('export const demoGuestCctvRoutes=',a);
assert(a>=0&&b>a,'Demo-only route sanitizer must exist');
const sandbox={};
vm.runInNewContext(cloud.slice(a,b),sandbox);
const valid={deviceType:'AV',ipAddress:'192.168.1.228',port:554,protocol:'RTSP',streamPath:'/stream1',
 username:'private-user',credentials:{ciphertext:'private-encrypted-secret'}};
const route=sandbox.demoGuestRoute(valid);
assert.equal(route,'rtsp://192.168.1.228:554/stream1','VIGI private IP matches Firestore and uses RTSP');
assert(!route.includes('private-user')&&!route.includes('private-encrypted-secret'),'no credentials or owner data in public route');
assert.equal(sandbox.demoGuestRoute({...valid,ipAddress:'8.8.8.8'}),null,'deny WAN IP exposure from guest endpoint');
assert.equal(sandbox.demoGuestRoute({...valid,ipAddress:'192.168.1.228@other.example'}),null,'deny userinfo/host injection');
assert.equal(sandbox.demoGuestRoute({...valid,streamPath:'/stream1?password=secret'}),null,'deny query-string secrets');
assert.equal(sandbox.demoGuestRoute({...valid,deviceType:'IoT'}),null,'deny sensors in CCTV response');
assert.equal(sandbox.demoGuestRoute({...valid,protocol:'HTTP',ipAddress:'192.168.1.227',port:8080,streamPath:'/videofeed'}),'http://192.168.1.227:8080/videofeed');
assert.match(cloud,/\.where\('plotId','==','plot-1'\)/,'guest endpoint scoped to one Demo Plot only');
assert.match(cloud,/a\.greenhouseId==='greenhouse-1'/,'guest endpoint scoped to Greenhouse 01');
assert.match(cloud,/\^section-\[1-3\]\$/,'guest endpoint accepts only three existing live slots');
assert.match(cloud,/return \{plotId:'plot-1',greenhouseId:'greenhouse-1',streams\}/,'guest response contains routes only');
assert.match(java,/getHttpsCallable\("demoGuestCctvRoutes"\)/,'signed-out Android calls public Demo-only config');
assert.match(java,/private void returnToDemoStreams\(\) \{[\s\S]*?loadGuestDemoStreams\(generation\);/,'logout resolves Firebase mapping');
